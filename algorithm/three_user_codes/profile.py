"""Exact Yao--Jafar three-user broadcast branches; no floating point."""
from __future__ import annotations

from dataclasses import dataclass
from fractions import Fraction
from itertools import permutations

from .linalg import Matrix, contains, intersection, quotient_rank, row_basis, row_sum


PERMUTATIONS = tuple(permutations(range(3)))


@dataclass(frozen=True)
class BroadcastProfile:
    first: tuple[int, ...]
    second: tuple[Fraction, ...]
    cost: Fraction

    @property
    def branches(self) -> tuple[Fraction, ...]:
        """F123,F132,F213,F231,F312,F321, then Q11,Q12,...,Q33."""
        return tuple(Fraction(x) for x in self.first) + self.second

    @property
    def doubled(self) -> tuple[int, ...]:
        return tuple(int(2 * x) for x in self.branches)


def conditional_rank(c: Matrix, a: Matrix) -> int:
    """dim(C + A) - dim(A), allowing redundant input rows."""
    return quotient_rank(c, a)


def broadcast_profile(side, augmented) -> BroadcastProfile:
    """Evaluate all fifteen additive branches of a three-user LCBC task.

    ``side[i]`` must be contained in ``augmented[i]``. Unlike ``Task``, this
    routine also accepts a fully informed-server task whose demands are not
    generated by the users' side information. All fifteen ranks use the
    actual function subspaces; joint entropy data alone do not suffice.
    """
    if len(side) != 3 or len(augmented) != 3:
        raise ValueError("three side and three augmented spaces are required")
    matrices = tuple(side) + tuple(augmented)
    if any(a.field != matrices[0].field or a.ncols != matrices[0].ncols for a in matrices):
        raise ValueError("all spaces must share their field and ambient dimension")
    side = tuple(row_basis(a) for a in side)
    augmented = tuple(row_basis(u) for u in augmented)
    if any(not contains(u, a) for a, u in zip(side, augmented)):
        raise ValueError("each augmented space must contain its side-information space")
    total = sum(u.nrows - a.nrows for a, u in zip(side, augmented))
    pair = {(i, j): intersection(augmented[i], augmented[j]) for i in range(3) for j in range(i + 1, 3)}

    def uij(i, j):
        return pair[tuple(sorted((i, j)))]

    triple = intersection(uij(0, 1), augmented[2])
    other_sums = tuple(row_sum(*(augmented[j] for j in range(3) if j != i))
                       for i in range(3))
    joint_rank = other_sums[0].nrows + conditional_rank(augmented[0], other_sums[0])
    # For A <= U and S the sum of the other two augmented spaces,
    # dim((U intersect S)/((U intersect S) intersect A))
    #   = dim(U)-dim(A)-dim(U+S)+dim(A+S).
    # All U+S are the same joint span. Only its dimension is needed:
    # avoid constructing three potentially large intersection bases.
    mixed_ranks = tuple(augmented[i].nrows - side[i].nrows - joint_rank
                        + other_sums[i].nrows + conditional_rank(side[i], other_sums[i])
                        for i in range(3))
    first = tuple(total - conditional_rank(uij(i, j), side[j]) - mixed_ranks[k]
                  for i, j, k in PERMUTATIONS)
    triple_ranks = tuple(conditional_rank(triple, side[l]) for l in range(3))
    second = []
    for i in range(3):
        j, k = (h for h in range(3) if h != i)
        pair_sum_rank = conditional_rank(row_sum(uij(i, j), uij(i, k)), side[i])
        for l in range(3):
            second.append(Fraction(2 * total - triple_ranks[l] - pair_sum_rank - mixed_ranks[j] - mixed_ranks[k], 2))
    second = tuple(second)
    return BroadcastProfile(first, second, max(tuple(Fraction(x) for x in first) + second))
